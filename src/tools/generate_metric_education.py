"""Generate the offline iOS metric descriptions from the reviewed editorial catalog."""
import argparse
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]


def generated_source():
    with (ROOT / 'docs/metrics/education.tsv').open() as stream:
        rows = list(csv.DictReader(stream, delimiter='|'))
    descriptions = {row['id']: row['description'] for row in rows}
    assert len(descriptions) == len(rows), 'Duplicate metric descriptions'
    aliases = json.loads((ROOT / 'docs/metrics/education-aliases.json').read_text())
    assert set(aliases.values()) <= descriptions.keys(), 'Alias without an explanation'
    # Do not turn unknown or ambiguous test names into an unrelated explanation.
    source = '''// Generated by src/tools/generate_metric_education.py. Edit docs/metrics instead.
import Foundation

public enum MetricEducation {
    public static func explanation(id: String, name: String) -> String? {
        if let description = descriptions[id] { return description }
        let key = name.lowercased().filter { $0.isLetter || $0.isNumber || $0 == "%" || $0 == "/" }
        guard let canonical = aliases[key] else { return nil }
        return descriptions[canonical]
    }

    public static let descriptions: [String: String] = [
'''
    for key, value in sorted(descriptions.items()):
        source += f'        {json.dumps(key, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False)},\n'
    source += '    ]\n\n    private static let aliases: [String: String] = [\n'
    for key, value in sorted(aliases.items()):
        source += f'        {json.dumps(key, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False)},\n'
    return source + '    ]\n}\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/shared/Core/MetricEducation.swift'
    content = generated_source()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('MetricEducation.swift is stale; run the generator.')
    else:
        target.write_text(content)
