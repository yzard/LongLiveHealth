pub(crate) fn key(name: &str) -> String {
    // Preserve percent and slash: ratios and percentages are separate tests.
    name.chars()
        .filter(|c| c.is_alphanumeric() || *c == '%' || *c == '/')
        .flat_map(char::to_lowercase)
        .collect()
}

